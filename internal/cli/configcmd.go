package cli

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"

	"github.com/daregod/ext-tags/internal/config"
	"github.com/daregod/ext-tags/internal/rules"
)

func (a *app) configCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "config",
		Short: "Inspect and create the configuration",
	}

	var (
		force bool
		full  bool
	)
	initCmd := &cobra.Command{
		Use:   "init [path]",
		Short: "Write a default configuration file",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			target := "ext-tags.yaml"
			if len(args) == 1 {
				target = args[0]
			}
			if _, err := os.Stat(target); err == nil && !force {
				return fmt.Errorf("%s already exists (use --force to overwrite)", target)
			}
			content := config.MinimalExample()
			if full {
				data, err := config.Default().Marshal()
				if err != nil {
					return err
				}
				header := "# ext-tags configuration (full)\n# Generated by: ext-tags config init --full\n\n" + config.TagReference() + "\n"
				content = append([]byte(header), data...)
			}
			if err := os.WriteFile(target, content, 0644); err != nil {
				return err
			}
			fmt.Printf("Wrote %s\n", target)
			return nil
		},
	}
	initCmd.Flags().BoolVar(&force, "force", false, "overwrite an existing file")
	initCmd.Flags().BoolVar(&full, "full", false, "write the complete configuration instead of a minimal example")

	validateCmd := &cobra.Command{
		Use:   "validate",
		Short: "Validate the effective configuration",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, label, err := a.effectiveConfig()
			if err != nil {
				return err
			}
			if _, err := rules.New(cfg); err != nil {
				return err
			}
			for _, warning := range cfg.Warnings() {
				fmt.Fprintf(os.Stderr, "warning: %s\n", warning)
			}
			fmt.Printf("ok: %s\n", label)
			return nil
		},
	}

	showCmd := &cobra.Command{
		Use:   "show",
		Short: "Print the effective configuration",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, _, err := a.effectiveConfig()
			if err != nil {
				return err
			}
			data, err := cfg.Marshal()
			if err != nil {
				return err
			}
			_, err = os.Stdout.Write(data)
			return err
		},
	}

	pathCmd := &cobra.Command{
		Use:   "path",
		Short: "Print the configuration file in use",
		Args:  cobra.NoArgs,
		Run: func(cmd *cobra.Command, args []string) {
			explicit := a.opts.configPath
			if explicit == "" {
				explicit = os.Getenv(config.EnvConfig)
			}
			layers := config.ResolveLayers(explicit)
			if layers.Empty() {
				fmt.Println("(built-in defaults)")
				return
			}
			if layers.Explicit != "" {
				fmt.Printf("explicit: %s\n", layers.Explicit)
			}
			if layers.User != "" {
				fmt.Printf("user:     %s\n", layers.User)
			}
			if layers.Project != "" {
				fmt.Printf("project:  %s\n", layers.Project)
			}
		},
	}

	cmd.AddCommand(initCmd, validateCmd, showCmd, pathCmd)
	return cmd
}
